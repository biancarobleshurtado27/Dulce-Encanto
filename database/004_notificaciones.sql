CREATE TABLE IF NOT EXISTS notificacion_estado (
 id INT PRIMARY KEY,
 huella VARCHAR(64) NOT NULL DEFAULT '',
 revision BIGINT NOT NULL DEFAULT 0
) ENGINE=InnoDB;
INSERT IGNORE INTO notificacion_estado (id) VALUES (1);
CREATE TABLE IF NOT EXISTS notificacion_envio (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 clave VARCHAR(120) NOT NULL UNIQUE,
 tipo VARCHAR(20) NOT NULL,
 estado VARCHAR(20) NOT NULL,
 detalle VARCHAR(250),
 fecha DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
